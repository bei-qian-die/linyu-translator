const lines = fs.readFileSync(P, 'utf8').split('\n');
let cur = null;
let changed = 0;
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/name: '([^']+)'/);
  if (m) cur = m[1];
  const w = lines[i].match(/^(\s*)words: \[.*\],$/);
  if (w && MAP[cur] && cur !== '淋淋' && cur !== '劳荣枝') {
    lines[i] = w[1] + 'words: [' + MAP[cur].map((s) => JSON.stringify(s)).join(', ') + '],';
    changed++;
    delete MAP[cur];
  }
}
